import { test, expect } from '@playwright/test';

test('preparer investigates October, corrects fixtures, and reviewer requests changes and signs off', async ({page}) => {
  const errors = [];
  page.on('pageerror',error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('row',{name:/September 2026/})).toContainText('Signed off');
  await page.getByLabel('Period',{exact:true}).selectOption('oct');
  await expect(page.getByRole('row',{name:/September 2026/})).toHaveCount(0);
  await page.getByLabel('Business line').selectOption('Annuities');
  await expect(page.getByText('No valuation runs')).toBeVisible();
  await page.getByLabel('Business line').selectOption('all');
  await page.getByRole('link',{name:/Life reserve valuation/}).click();
  await expect(page.getByText('Batch completed')).toBeVisible();
  await expect(page.getByRole('button',{name:'Submit for review'})).toBeDisabled();
  await page.getByRole('link',{name:'Inputs',exact:true}).click();
  await page.getByRole('button',{name:'Run input checks'}).click();
  await expect(page.getByRole('button',{name:'Running checks…'})).toBeDisabled();
  await expect(page.getByRole('row',{name:/Assumptions version/})).toContainText('Failed');
  await page.getByRole('button',{name:'Select replacement'}).click();
  await page.getByLabel('Available files').selectOption('assumptions-v8');
  await page.getByRole('button',{name:'Associate file'}).click();
  await expect(page.getByText('Files changed since the last check')).toBeVisible();
  await page.getByRole('button',{name:'Run input checks'}).click();
  await expect(page.getByRole('row',{name:/Assumptions version/})).toContainText('Passed');

  await page.getByRole('link',{name:'Overview',exact:true}).click();
  const exception = page.getByRole('row',{name:/Reserve roll-forward/});
  await expect(exception).toContainText('CAD +1.2M');
  await exception.getByRole('button').click();
  const panel = page.getByRole('complementary',{name:'Selected item'});
  await expect(panel.getByText('106.2',{exact:true})).toBeVisible();
  await panel.getByRole('button',{name:'Break down by product'}).click();
  const figures = await panel.getByRole('table').innerText();
  await expect(panel.getByRole('row',{name:/Term Life/})).toContainText('+0.9');
  await expect(panel.getByRole('row',{name:/Whole Life/})).toContainText('+0.3');
  await panel.getByRole('row',{name:/Term Life/}).getByRole('button',{name:'AXIS',exact:true}).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog.getByText('B3',{exact:true})).toBeVisible();
  await expect(dialog.locator('.highlight')).toHaveText('68.9');
  await dialog.getByRole('button',{name:'Close dialog'}).click();
  await panel.getByRole('button',{name:'AI',exact:true}).click();
  await panel.getByRole('button',{name:'Investigate with AI'}).click();
  await expect(panel.getByText('Cause unconfirmed')).toBeVisible();
  expect(await panel.getByRole('table').innerText()).toBe(figures);
  await panel.getByLabel('Ask about this exception').fill('Can you break this down by product?');
  await panel.getByRole('button',{name:'Ask',exact:true}).click();
  await expect(panel.getByRole('table')).toHaveCount(2);
  await panel.getByRole('button',{name:'Activity'}).click();
  await panel.getByLabel('Note',{exact:true}).fill('Confirmed the split against the output.');
  await panel.getByRole('button',{name:'Add note'}).click();
  await expect(panel.getByText('Confirmed the split against the output.')).toBeVisible();
  await panel.getByRole('button',{name:'Close panel'}).click();
  await expect(exception).toHaveClass('selected');

  await page.getByRole('link',{name:'Variance'}).click();
  await page.getByRole('button',{name:'Total life reserves',exact:true}).click();
  await expect(page.getByRole('row',{name:/Whole Life/})).toContainText('+0.3');
  await page.getByRole('button',{name:/Whole Life: unexplained difference/}).click();
  await expect(dialog.getByText('37.3 − 37.0 = +0.3')).toBeVisible();
  await dialog.getByRole('button',{name:'Close dialog'}).click();

  await page.getByRole('link',{name:'Outputs',exact:true}).click();
  const renewalPicker = page.getByRole('row',{name:/Renewal output/}).getByRole('button',{name:'Associate output'});
  await renewalPicker.click();
  await page.getByLabel('Available files').selectOption('');
  await page.getByRole('button',{name:'Associate file'}).click();
  await page.getByRole('button',{name:'Run output checks'}).click();
  await expect(page.getByRole('row',{name:/Renewal record count/})).toContainText('Not run');
  await renewalPicker.click();
  await page.getByLabel('Available files').selectOption('renewal-oct');
  await page.getByRole('button',{name:'Associate file'}).click();
  await expect(page.getByRole('status').filter({hasText:'Files changed since the last check'})).toBeVisible();
  await page.getByRole('row',{name:/Closing reserves.*LIFE_CA_Reserve/}).getByRole('button',{name:'Associate output'}).click();
  await page.getByLabel('Available files').selectOption('reserve-corrected');
  await page.getByRole('button',{name:'Associate file'}).click();
  await page.getByRole('button',{name:'Run output checks'}).click();
  await expect(page.getByRole('row',{name:/Reserve roll-forward/})).toContainText('Passed');
  await page.getByRole('button',{name:'Attempt history'}).click();
  await page.getByLabel('Check attempt').selectOption('O-001');
  await page.getByRole('button',{name:/Reserve roll-forward/}).click();
  await panel.getByRole('button',{name:'AI',exact:true}).click();
  await expect(panel.getByText('Cause unconfirmed')).toHaveCount(2);
  await panel.getByRole('button',{name:'Activity'}).click();
  await expect(panel.getByText(/Output checks · Passed · O-003/)).toBeVisible();
  await page.getByLabel('Check attempt').selectOption('O-003');
  await expect(panel).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole('row',{name:/Reserve roll-forward/})).toContainText('Passed');
  await page.getByRole('button',{name:'Submit for review'}).click();
  await expect(page.getByRole('heading',{name:'Submitted version v1'})).toBeVisible();
  await page.getByLabel('Demo role').selectOption('Reviewer');
  await expect(page.getByRole('heading',{name:'My reviews'})).toBeVisible();
  await page.getByRole('link',{name:/October 2026/}).click();
  await expect(page.getByText('v1 · Read-only')).toBeVisible();
  await page.getByRole('link',{name:'Outputs',exact:true}).click();
  await expect(page.getByRole('button',{name:'Run output checks'})).toHaveCount(0);
  await expect(page.getByRole('row',{name:/Reserve roll-forward/})).toContainText('105.0');
  await page.getByRole('link',{name:'Review',exact:true}).click();
  await expect(page.getByRole('button',{name:'Request changes'})).toBeDisabled();
  await page.getByLabel('Review note').fill('Please resubmit after confirming the output.');
  await page.getByRole('button',{name:'Request changes'}).click();
  await expect(page.getByText('v1 · Changes requested')).toBeVisible();
  await page.getByLabel('Demo role').selectOption('Preparer');
  await page.getByRole('link',{name:'Open working run'}).click();
  await page.getByRole('button',{name:'Submit for review'}).click();
  await expect(page.getByRole('heading',{name:'Submitted version v2'})).toBeVisible();
  await page.getByLabel('Demo role').selectOption('Reviewer');
  await page.getByRole('link',{name:/October 2026/}).click();
  await page.getByRole('button',{name:'Sign off'}).click();
  await expect(page.getByText('v2 · Signed off')).toBeVisible();
  await expect(page.getByText(/Daniel Roy · .* ET/).last()).toBeVisible();
  await page.getByRole('navigation',{name:'Workspace'}).getByRole('link',{name:'My reviews',exact:true}).click();
  await expect(page.getByRole('row',{name:/October 2026/})).toContainText('Signed off');
  expect(errors).toEqual([]);
});

test('on a narrower screen the evidence panel overlays the table and closing retains selection', async ({page}) => {
  await page.setViewportSize({width:1100,height:800});
  await page.goto('/');
  await page.getByRole('link',{name:/October 2026/}).click();
  const row = page.getByRole('row',{name:/Reserve roll-forward/});
  await row.getByRole('button').click();
  const panel = page.getByRole('complementary',{name:'Selected item'});
  await expect(panel).toHaveCSS('position','fixed');
  await panel.getByRole('button',{name:'Close panel'}).click();
  await expect(panel).toHaveCount(0);
  await expect(row).toHaveClass('selected');
});

test('preparer creates a persisted valuation run under the selected period', async ({page}) => {
  await page.goto('/#/runs');
  await page.getByLabel('Period',{exact:true}).selectOption('oct');
  await page.getByRole('button',{name:'New valuation run'}).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Valuation name').fill('September recheck');
  await dialog.getByLabel('Valuation period').selectOption('sep');
  await dialog.getByLabel('AXIS Batch ID').fill('014');
  await dialog.getByRole('button',{name:'Create run'}).click();
  await expect(dialog.getByRole('alert')).toHaveText('Batch 014 already exists');
  await dialog.getByLabel('AXIS Batch ID').fill('015');
  await dialog.getByRole('button',{name:'Create run'}).click();
  await expect(page.getByRole('heading',{name:'September recheck'})).toBeVisible();
  await expect(page.getByRole('button',{name:'Submit for review'})).toBeDisabled();

  await page.getByRole('link',{name:'Inputs',exact:true}).click();
  await expect(page.getByText('No check attempts')).toBeVisible();
  await page.getByRole('button',{name:'Run input checks'}).click();
  await expect(page.getByRole('row',{name:/Assumptions version/})).toContainText('Passed');
  await page.getByRole('link',{name:'Outputs',exact:true}).click();
  await expect(page.getByText('No check attempts')).toBeVisible();
  await page.getByRole('button',{name:'Run output checks'}).click();
  await expect(page.getByRole('row',{name:/Reserve roll-forward/})).toContainText('Passed');
  await page.getByRole('link',{name:'Back to worklist'}).click();
  await expect(page.getByLabel('Period',{exact:true})).toHaveValue('sep');
  await expect(page.getByRole('row',{name:/September recheck/})).toContainText('Draft');
  await page.reload();
  await expect(page.getByRole('row',{name:/September recheck/})).toContainText('Batch 015');
  await expect(page.getByRole('row',{name:/Batch 013/})).toContainText('Signed off');
  await page.getByLabel('Demo role').selectOption('Reviewer');
  await page.getByRole('navigation',{name:'Workspace'}).getByRole('link',{name:'Valuation runs'}).click();
  await expect(page.getByRole('button',{name:'New valuation run'})).toHaveCount(0);
});
